def solution_for(mistake_type: str) -> dict[str, Any] | None:
    item = MISTAKES.get(mistake_type)
    if not item:
        return None
    return {"code": mistake_type, "mistake_title": item["title"], "category": item["category"], **item["solution"]}


def catalogue() -> list[dict[str, Any]]:
    return [
        {"type": k, "title": v["title"], "category": v["category"], "category_title": CATEGORIES[v["category"]],
         "explanation": v["explanation"], "solution": v["solution"]}
        for k, v in MISTAKES.items()
    ]
